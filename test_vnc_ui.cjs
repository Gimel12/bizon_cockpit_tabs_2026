const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('cockpit_vnc/index.html','utf8');
const source=fs.readFileSync('cockpit_vnc/secure-vnc.js','utf8').replace(/^import RFB[^\n]+\n/,'');
let passed=0;
function check(name,fn){fn();passed++;console.log('PASS '+name);}
function setup(){
 const dom=new JSDOM(html,{runScripts:'outside-only'}),w=dom.window,procs=[],rfbs=[],timers=new Map();let timerId=0;
 w.setTimeout=fn=>{timers.set(++timerId,fn);return timerId;};w.clearTimeout=id=>timers.delete(id);
 w.cockpit={spawn(){const p={closed:0,stream(cb){this.data=cb;return this;},then(cb){this.done=cb;return this;},catch(cb){this.fail=cb;return this;},close(){this.closed++;this.fail(new Error('closed'));}};procs.push(p);return p;},channel(){return{addEventListener(){},send(){},close(){}};}};
 w.RFB=class{constructor(el,socket,opts){this.listeners={};this.opts=opts;rfbs.push(this);el.appendChild(w.document.createElement('canvas'));}addEventListener(n,fn){this.listeners[n]=fn;}emit(n,detail={}){this.listeners[n]?.({detail});}disconnect(){this.closed=true;this.emit('disconnect',{clean:true});}};
 w.eval(source);
 const el=id=>w.document.getElementById(id),click=id=>el(id).click(),state=()=>w.document.body.dataset.state;
 const config=()=>procs.at(-1).data(JSON.stringify({port:5910,password:'testonly'})+'\n');
 return{w,dom,procs,rfbs,timers,el,click,state,config};
}
const t=setup();
check('manual connection; nothing starts on page load',()=>{assert.equal(t.procs.length,0);assert(!t.el('connect').disabled);assert(t.el('fullscreen').disabled);});
t.click('connect');
check('starting state has cancel and progress',()=>{assert.equal(t.state(),'starting');assert(!t.el('cancel').hidden);assert(t.el('connect').hidden);assert.equal(t.procs.length,1);});
t.click('connect');check('repeated connect cannot spawn duplicate desktops',()=>assert.equal(t.procs.length,1));
t.procs[0].data('{"port":5910,');
check('split startup messages wait for a complete line',()=>assert.equal(t.rfbs.length,0));
t.procs[0].data('"password":"testonly"}\n');
check('server-ready state still waits for authentication',()=>{assert.equal(t.state(),'connecting');assert.equal(t.rfbs.length,1);assert.equal(t.rfbs[0].scaleViewport,true);assert.equal(t.rfbs[0].resizeSession,true);});
t.rfbs[0].emit('connect');
check('successful authentication reveals desktop and controls',()=>{assert.equal(t.state(),'connected');assert(t.el('welcome').hidden);assert(!t.el('toolbar').hidden);assert(!t.el('fullscreen').disabled);assert.equal(t.timers.size,0);});
t.click('disconnect');
check('disconnect closes transport and backend, clears screen',()=>{assert.equal(t.state(),'disconnected');assert.equal(t.procs[0].closed,1);assert(t.rfbs[0].closed);assert.equal(t.el('screen').children.length,0);assert(!t.el('connect').disabled);});
t.click('connect');t.procs[0].done();t.procs[0].fail(new Error('late'));t.rfbs[0].emit('connect');
check('old callbacks do not corrupt a new connection',()=>assert.equal(t.state(),'starting'));
t.click('cancel');
check('cancel stops startup and clears its timeout',()=>{assert.equal(t.state(),'disconnected');assert.equal(t.procs[1].closed,1);assert.equal(t.timers.size,0);});
t.click('connect');[...t.timers.values()][0]();
check('startup timeout offers retry and closes backend',()=>{assert.equal(t.state(),'error');assert.equal(t.procs[2].closed,1);assert.equal(t.el('connect').textContent,'Try again →');});
t.click('connect');t.config();t.rfbs.at(-1).emit('securityfailure');
check('authentication failure returns an actionable error',()=>{assert.equal(t.state(),'error');assert.match(t.el('welcome-description').textContent,/authenticate/);});
t.click('connect');t.config();t.rfbs.at(-1).emit('disconnect',{clean:true});
check('closing before authentication is an error',()=>assert.equal(t.state(),'error'));
t.click('connect');t.procs.at(-1).data('{"port":22,"password":"testonly"}\n');
check('invalid port fails closed',()=>assert.equal(t.state(),'error'));
t.click('connect');t.procs.at(-1).data('x'.repeat(8193));
check('oversized startup response fails closed',()=>assert.equal(t.state(),'error'));
t.click('connect');t.procs.at(-1).fail(new Error('PRIVATE CREDENTIAL'));
check('raw backend errors are not exposed to the UI',()=>{assert.equal(t.state(),'error');assert(!t.w.document.body.textContent.includes('PRIVATE CREDENTIAL'));});
t.click('connect');t.config();t.rfbs.at(-1).emit('connect');t.rfbs.at(-1).emit('disconnect',{clean:false});
check('network disconnect offers retry',()=>{assert.equal(t.state(),'error');assert.match(t.el('welcome-description').textContent,/network/);});
t.click('connect');t.config();t.rfbs.at(-1).emit('connect');t.procs.at(-1).done();
check('normal session exit restores landing card',()=>assert.equal(t.state(),'disconnected'));
t.click('connect');t.w.dispatchEvent(new t.w.Event('beforeunload'));
check('page unload closes active backend',()=>assert.equal(t.procs.at(-1).closed,1));
t.dom.window.close();
console.log(`${passed}/${passed} VNC UI lifecycle checks passed`);
